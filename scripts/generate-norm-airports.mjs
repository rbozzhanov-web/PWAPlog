/**
 * Generates packages/core/src/crew-pay/normAirports.ts.
 *
 * `normLookup` has to canonicalise airport codes to ICAO so a logbook row saved as TSE matches a
 * published row saying NQZ. It used to do that through `daynight/airportDb`, which eagerly parses
 * an 855 KB worldwide dataset at module load — and because the core barrel re-exports normLookup,
 * every byte of it landed in the app's entry chunk and was parsed on every launch.
 *
 * Only a few hundred of those airports can ever matter: a code that does not resolve to an airport
 * in the published norms table cannot match a published sector whichever way it is spelled. So this
 * emits just those airports, keyed by every alias the dataset knows for them, and the lookup keeps
 * its behaviour without the dataset.
 *
 * Re-run with `npm run generate:norm-airports` after changing the norms table or the dataset. The
 * equivalence test in crew-pay/__tests__/normAirports.test.ts fails if the generated file drifts.
 */
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../packages/core/src/', import.meta.url);
const ICAO_RE = /^[A-Z]{4}$/;

// Mirrors airportDb's CODE_OVERRIDES. Kept in step by the equivalence test.
const CODE_OVERRIDES = { TSE: 'UACC', FRU: 'UCFM', UAFM: 'UCFM' };

const airports = JSON.parse(await readFile(new URL('daynight/assets/airports.json', root), 'utf8'));
const normsTable = await readFile(new URL('crew-pay/normsTable.ts', root), 'utf8');

const byIata = new Map();
const byIcao = new Map();
const icaoOf = new Map();
for (const record of airports) {
  if (record.iata) byIata.set(record.iata.toUpperCase(), record);
  if (record.icao) byIcao.set(record.icao.toUpperCase(), record);
  const icao = record.icao?.toUpperCase() ?? record.ident?.toUpperCase();
  if (icao && ICAO_RE.test(icao)) icaoOf.set(record, icao);
}

const findRecord = (code) => byIcao.get(code) ?? byIata.get(code);
function toIcao(code) {
  const normalized = code.trim().toUpperCase();
  if (!normalized) return normalized;
  if (CODE_OVERRIDES[normalized]) return CODE_OVERRIDES[normalized];
  const record = findRecord(normalized);
  return (record && icaoOf.get(record)) ?? normalized;
}

// The published table is a literal block of "DEP ARR H:MM" lines, kept as published.
const published = [...normsTable.matchAll(/^([A-Z]{3}) ([A-Z]{3}) \d{1,2}:\d{2}$/gm)];
if (published.length === 0) throw new Error('No published sectors found in normsTable.ts.');
const tableIcaos = new Set(published.flatMap(([, dep, arr]) => [toIcao(dep), toIcao(arr)]));

const aliases = new Map();
const add = (alias, icao) => {
  if (!alias) return;
  const key = alias.trim().toUpperCase();
  if (key) aliases.set(key, icao);
};
for (const record of airports) {
  const icao = icaoOf.get(record);
  if (!icao || !tableIcaos.has(icao)) continue;
  add(record.iata, icao);
  add(record.icao, icao);
  add(record.ident, icao);
}
for (const [alias, icao] of Object.entries(CODE_OVERRIDES)) {
  if (tableIcaos.has(icao)) add(alias, icao);
}

const entries = [...aliases].sort(([left], [right]) => left.localeCompare(right));
const body = entries.map(([alias, icao]) => `  ${alias}: '${icao}',`).join('\n');

await writeFile(
  new URL('crew-pay/normAirports.ts', root),
  `/* eslint-disable */
// GENERATED by scripts/generate-norm-airports.mjs — do not edit by hand.
//
// Every alias the airport dataset knows for an airport that appears in the published CrewPay norms
// table, mapped to that airport's ICAO code. Codes outside this set cannot match a published
// sector however they are spelled, so they are passed through uppercased, exactly as
// airportDb.toIcaoCode would leave an unresolved code.
//
// ${entries.length} aliases covering ${tableIcaos.size} airports, standing in for an 855 KB dataset.

const NORM_AIRPORTS: Record<string, string> = {
${body}
};

/** Canonicalises an airport code to ICAO, for norms-table lookups only. */
export function toNormIcaoCode(code: string): string {
  const normalized = code.trim().toUpperCase();
  return NORM_AIRPORTS[normalized] ?? normalized;
}
`,
);

console.log(`normAirports.ts: ${entries.length} aliases, ${tableIcaos.size} airports.`);
